function parseDailySeries() {
  return RAW_DAILY_CSV.trim()
    .split("\n")
    .map((line) => {
      const [date, segmentId, detections, frpSum, activeCells] = line.split(",");
      return {
        date,
        segmentId: Number(segmentId),
        detections: Number(detections),
        frpSum: Number(frpSum),
        activeCells: Number(activeCells),
        cellsSampled: 5000,
      };
    });
}

// Serie giornaliera reale, aggregata dal campione disponibile (5.000 celle per
// segmento, 15.000 celle totali). Copre i 3 segmenti utilizzabili; i segmenti
// troppo corti (1, 2, 3) non producono righe nel pannello campionato.
export const DAILY_SERIES = parseDailySeries();

function buildCalendarSeries() {
  const byDate = new Map(DAILY_SERIES.map((row) => [row.date, row]));
  const start = new Date(`${TIME_SEGMENTS[0].start}T00:00:00Z`);
  const end = new Date(`${TIME_SEGMENTS[TIME_SEGMENTS.length - 1].end}T00:00:00Z`);
  const days = [];
  for (let cursor = start; cursor <= end; cursor.setUTCDate(cursor.getUTCDate() + 1)) {
    const date = cursor.toISOString().slice(0, 10);
    const row = byDate.get(date);
    days.push(
      row
        ? { ...row, missing: false }
        : { date, segmentId: null, detections: null, frpSum: null, activeCells: null, cellsSampled: null, missing: true }
    );
  }
  return days;
}

// Serie calendariale continua (un punto per ogni giorno fra l'inizio del
// segmento 0 e la fine del segmento 5): i giorni senza dati nel campione
// restano `null`, così i grafici mostrano un'interruzione reale invece di
// collegare con una linea due segmenti separati da mesi di assenza dati.
export const CALENDAR_SERIES = buildCalendarSeries();

export function getSegmentSeries(segmentId) {
  if (segmentId === undefined || segmentId === null || segmentId === "all") {
    return CALENDAR_SERIES;
  }
  return DAILY_SERIES.filter((row) => row.segmentId === Number(segmentId));
}

export function getRecentWindow(days) {
  return CALENDAR_SERIES.slice(-days);
}

export const SEGMENT_SUMMARIES = TIME_SEGMENTS.map((segment) => {
  const rows = DAILY_SERIES.filter((row) => row.segmentId === segment.id);
  const totalDetections = rows.reduce((sum, row) => sum + row.detections, 0);
  const totalFrp = rows.reduce((sum, row) => sum + row.frpSum, 0);
  return {
    ...segment,
    rowsInSample: rows.length,
    totalDetections,
    totalFrp,
    mlRows: segment.usableForModel ? (segment.id === 0 ? 117817 : 77016) : 0,
  };
});

// Finestre di embargo di 7 giorni applicate ai bordi di ciascun segmento
// utilizzabile, per separare temporalmente train, validation e test.
